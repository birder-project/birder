        valid_mask = pad_sequence(
            [patches.new_ones(patches.size(0), dtype=torch.bool) for patches in patch_sequences],
            batch_first=True,
        )

        grid_sizes_tensor = torch.tensor(grid_sizes, dtype=torch.int64, device=padded_patches.device)
        return (padded_patches, grid_sizes_tensor, valid_mask)

