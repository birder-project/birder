    def _random_offset(grid_size: int, overlap_size: int) -> int:
        max_offset = grid_size - overlap_size
        if max_offset == 0:
            return 0

        return int(torch.randint(max_offset + 1, ()).item())

    def _mixup(
        self,
        patch_sequences: list[torch.Tensor],
        grid_sizes: list[tuple[int, int]],
        targets: torch.Tensor,
    ) -> tuple[list[torch.Tensor], torch.Tensor]:
        lambda_param = float(self._lambda_dist.sample().item())
        mixed_sequences: list[torch.Tensor] = []
        effective_lambdas: list[float] = []

        for idx, (patches, (grid_h, grid_w)) in enumerate(zip(patch_sequences, grid_sizes)):
            donor_idx = (idx - 1) % len(patch_sequences)
            donor_patches = patch_sequences[donor_idx]
            donor_grid_h, donor_grid_w = grid_sizes[donor_idx]

            overlap_h = min(grid_h, donor_grid_h)
            overlap_w = min(grid_w, donor_grid_w)
            destination_top = self._random_offset(grid_h, overlap_h)
            destination_left = self._random_offset(grid_w, overlap_w)
            source_top = self._random_offset(donor_grid_h, overlap_h)
            source_left = self._random_offset(donor_grid_w, overlap_w)

            patch_grid = patches.reshape(grid_h, grid_w, -1).clone()
            donor_grid = donor_patches.reshape(donor_grid_h, donor_grid_w, -1)
            destination_region = patch_grid[
                destination_top : destination_top + overlap_h,
                destination_left : destination_left + overlap_w,
            ]
            source_region = donor_grid[
                source_top : source_top + overlap_h,
                source_left : source_left + overlap_w,
            ]
            destination_region.mul_(lambda_param).add_(source_region, alpha=1.0 - lambda_param)
            mixed_sequences.append(patch_grid.flatten(0, 1))

            overlap_fraction = (overlap_h * overlap_w) / (grid_h * grid_w)
            effective_lambdas.append(1.0 - ((1.0 - lambda_param) * overlap_fraction))

        targets = F.one_hot(targets, num_classes=self.num_classes).to(  # pylint: disable=not-callable
            dtype=patch_sequences[0].dtype
        )
        donor_targets = targets.roll(1, dims=0)
        lambda_tensor = targets.new_tensor(effective_lambdas).unsqueeze(1)
        targets.mul_(lambda_tensor).add_(donor_targets * (1.0 - lambda_tensor))

        return (mixed_sequences, targets)

