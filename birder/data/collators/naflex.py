class NaFlexMixupTrainingCollator(NaFlexTrainingCollator):
    """
    Apply regional MixUp to variable-size patch grids before padding

    Each sample is paired with the preceding sample in the batch. The largest patch
    rectangle shared by the two grids is blended at independently sampled source and
    destination positions. The recipient grid remains unchanged and the soft-target
    weights account for the fraction of its patches that were mixed.

    The variable-size regional MixUp strategy is adapted from timm's NaFlex MixUp:
    https://github.com/huggingface/pytorch-image-models/blob/main/timm/data/naflex_mixup.py

    Parameters
    ----------
    patch_size
        Height and width of each square image patch in fixed mode.
    num_classes
        Number of classes used for one-hot encoding.
    alpha
        Hyperparameter of the Beta distribution used for MixUp.
    p
        Probability of applying MixUp to a batch.
    """

    def __init__(self, patch_size: Optional[int], num_classes: int, alpha: float, p: Optional[float] = None) -> None:
        super().__init__(patch_size)
        if num_classes < 1:
            raise ValueError(f"Number of classes must be positive, got {num_classes}")
        if alpha <= 0:
            raise ValueError(f"Alpha must be positive, got {alpha}")
        if p is not None and (p < 0.0 or p > 1.0):
            raise ValueError(f"Probability must be in range [0, 1], got {p}")

        if p is None:
            p = 0.5

        self.num_classes = num_classes
        self.p = p
        self._lambda_dist = torch.distributions.Beta(alpha, alpha)

    @staticmethod
    def _random_offset(grid_size: int, overlap_size: int) -> int:
        max_offset = grid_size - overlap_size
        if max_offset == 0:
            return 0

        return int(torch.randint(max_offset + 1, ()).item())

    def _mixup(
        self,
        patch_sequences: list[torch.Tensor],
        grid_sizes: list[tuple[int, int]],
        targets: torch.Tensor,
    ) -> tuple[list[torch.Tensor], torch.Tensor]:
        lambda_param = float(self._lambda_dist.sample().item())
        mixed_sequences: list[torch.Tensor] = []
        effective_lambdas: list[float] = []

        for idx, (patches, (grid_h, grid_w)) in enumerate(zip(patch_sequences, grid_sizes)):
            donor_idx = (idx - 1) % len(patch_sequences)
            donor_patches = patch_sequences[donor_idx]
            donor_grid_h, donor_grid_w = grid_sizes[donor_idx]

            overlap_h = min(grid_h, donor_grid_h)
            overlap_w = min(grid_w, donor_grid_w)
            destination_top = self._random_offset(grid_h, overlap_h)
            destination_left = self._random_offset(grid_w, overlap_w)
            source_top = self._random_offset(donor_grid_h, overlap_h)
            source_left = self._random_offset(donor_grid_w, overlap_w)

            patch_grid = patches.reshape(grid_h, grid_w, -1).clone()
            donor_grid = donor_patches.reshape(donor_grid_h, donor_grid_w, -1)
            destination_region = patch_grid[
                destination_top : destination_top + overlap_h,
                destination_left : destination_left + overlap_w,
            ]
            source_region = donor_grid[
                source_top : source_top + overlap_h,
                source_left : source_left + overlap_w,
            ]
            destination_region.mul_(lambda_param).add_(source_region, alpha=1.0 - lambda_param)
            mixed_sequences.append(patch_grid.flatten(0, 1))

            overlap_fraction = (overlap_h * overlap_w) / (grid_h * grid_w)
            effective_lambdas.append(1.0 - ((1.0 - lambda_param) * overlap_fraction))

        targets = F.one_hot(targets, num_classes=self.num_classes).to(  # pylint: disable=not-callable
            dtype=patch_sequences[0].dtype
        )
        donor_targets = targets.roll(1, dims=0)
        lambda_tensor = targets.new_tensor(effective_lambdas).unsqueeze(1)
        targets.mul_(lambda_tensor).add_(donor_targets * (1.0 - lambda_tensor))

        return (mixed_sequences, targets)

    def __call__(self, batch: list[tuple[Any, ...]]) -> tuple[Any, ...]:
        batch_fields = list(zip(*batch))
        images, patch_size = self._resolve_inputs(batch_fields[self.input_offset])
        targets = default_collate(list(batch_fields[1]))
        patch_sequences, grid_sizes = self._patchify_images(images, patch_size)

        if len(patch_sequences) > 1 and (self.p == 1.0 or torch.rand(()).item() < self.p):
            patch_sequences, targets = self._mixup(patch_sequences, grid_sizes, targets)

        return (self._collate_inputs(patch_sequences, grid_sizes), targets)


