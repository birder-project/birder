class SimDINOv2Teacher(DINOv2Teacher):
    def forward(  # type: ignore[override]
        self,
        x: torch.Tensor,
        n_crops: int,
        upper_bound: int,
        mask_indices_list: torch.Tensor,
        target_feature_size: Optional[tuple[int, int]] = None,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        # if n_crops != 2:
        #     raise ValueError("SimDINO v2 requires two global crops")

        embedding, patches = super().forward(x, n_crops, upper_bound, mask_indices_list, target_feature_size)
        # DINO v2 swaps global views so A is matched to B in the cross-view loss. The MCR loss needs
        # the original order to exclude matching views and average matching teacher and student features
        second, first = embedding.chunk(2)
        return (torch.concat((first, second)), patches)
