def _fuse_conv_bn(module: Conv2dNormActivation) -> None:
    conv = module[0]
    norm = module[1]
    fused_conv = copy.deepcopy(conv)
    fused_conv.weight, fused_conv.bias = fuse_conv_bn_weights(
        fused_conv.weight,
        fused_conv.bias,
        norm.running_mean,
        norm.running_var,
        norm.eps,
        norm.weight,
        norm.bias,
    )

    module[0] = fused_conv
    module[1] = nn.Identity()


def _clamped_box_cxcywh_to_xyxy(boxes: torch.Tensor) -> torch.Tensor:
    center = boxes[..., :2]
    half_size = 0.5 * boxes[..., 2:].clamp(min=0)

    return torch.concat((center - half_size, center + half_size), dim=-1)


def _weighting_function(reg_max: int, up: torch.Tensor, reg_scale: torch.Tensor) -> torch.Tensor:
    upper_bound = up.abs() * reg_scale.abs()
    outer_bound = 2 * upper_bound
    step = (upper_bound + 1).pow(2 / (reg_max - 2))
    exponents = torch.arange(1, reg_max // 2, dtype=up.dtype, device=up.device)
    inner_values = step.pow(exponents)

    return torch.concat([-outer_bound, -inner_values.flip(0) + 1, torch.zeros_like(up), inner_values - 1, outer_bound])


def _translate_gt(
    gt: torch.Tensor, reg_max: int, reg_scale: torch.Tensor, up: torch.Tensor
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    gt = gt.reshape(-1)
    function_values = _weighting_function(reg_max, up, reg_scale)
    differences = function_values.unsqueeze(0) - gt.unsqueeze(1)
    indices = ((differences <= 0).sum(dim=1) - 1).float()
    weight_right = torch.zeros_like(indices)
    weight_left = torch.zeros_like(indices)

    valid_mask = (indices >= 0) & (indices < reg_max)
    valid_indices = indices[valid_mask].long()
    left_values = function_values[valid_indices]
    right_values = function_values[valid_indices + 1]
    left_differences = (gt[valid_mask] - left_values).abs()
    right_differences = (right_values - gt[valid_mask]).abs()
    weight_right[valid_mask] = left_differences / (left_differences + right_differences)
    weight_left[valid_mask] = 1 - weight_right[valid_mask]

    negative_mask = indices < 0
    weight_left[negative_mask] = 1
    indices[negative_mask] = 0

    positive_mask = indices >= reg_max
    weight_right[positive_mask] = 1
    indices[positive_mask] = reg_max - 0.1

    return (indices, weight_right, weight_left)


def _distance_to_bbox(points: torch.Tensor, distance: torch.Tensor, reg_scale: torch.Tensor) -> torch.Tensor:
    reg_scale = reg_scale.abs()
    x1 = points[..., 0] - (0.5 * reg_scale + distance[..., 0]) * (points[..., 2] / reg_scale)
    y1 = points[..., 1] - (0.5 * reg_scale + distance[..., 1]) * (points[..., 3] / reg_scale)
    x2 = points[..., 0] + (0.5 * reg_scale + distance[..., 2]) * (points[..., 2] / reg_scale)
    y2 = points[..., 1] + (0.5 * reg_scale + distance[..., 3]) * (points[..., 3] / reg_scale)

    return box_ops.box_convert(torch.stack([x1, y1, x2, y2], dim=-1), in_fmt="xyxy", out_fmt="cxcywh")


def _bbox_to_distance(
    points: torch.Tensor, bbox: torch.Tensor, reg_max: int, reg_scale: torch.Tensor, up: torch.Tensor
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    reg_scale = reg_scale.abs()
    left = (points[:, 0] - bbox[:, 0]) / (points[:, 2] / reg_scale + 1e-16) - 0.5 * reg_scale
    top = (points[:, 1] - bbox[:, 1]) / (points[:, 3] / reg_scale + 1e-16) - 0.5 * reg_scale
    right = (bbox[:, 2] - points[:, 0]) / (points[:, 2] / reg_scale + 1e-16) - 0.5 * reg_scale
    bottom = (bbox[:, 3] - points[:, 1]) / (points[:, 3] / reg_scale + 1e-16) - 0.5 * reg_scale
    distances, weight_right, weight_left = _translate_gt(
        torch.stack([left, top, right, bottom], dim=-1), reg_max, reg_scale, up
    )

    return (distances.clamp(min=0, max=reg_max - 0.1).reshape(-1).detach(), weight_right, weight_left)


class SCDown(nn.Module):
    """Spatial-channel decoupled downsampling block"""

    def __init__(self, in_channels: int, out_channels: int) -> None:
        super().__init__()
        self.pointwise_conv = Conv2dNormActivation(in_channels, out_channels, kernel_size=(1, 1), activation_layer=None)
        self.depthwise_conv = Conv2dNormActivation(
            out_channels, out_channels, kernel_size=(3, 3), stride=(2, 2), groups=out_channels, activation_layer=None
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.depthwise_conv(self.pointwise_conv(x))


class CSPLayer(nn.Module):
    def __init__(self, in_channels: int, out_channels: int, num_blocks: int) -> None:
        super().__init__()
        self.conv1 = Conv2dNormActivation(in_channels, out_channels, kernel_size=(1, 1), activation_layer=nn.SiLU)
        self.conv2 = Conv2dNormActivation(in_channels, out_channels, kernel_size=(1, 1), activation_layer=nn.SiLU)
        self.bottlenecks = nn.Sequential(
            *[
                RepVggBlock(
                    in_channels=out_channels,
                    out_channels=out_channels,
                    kernel_size=3,
                    stride=1,
                    padding=1,
                    groups=1,
                    use_se=False,
                    reparameterized=False,
                    act_layer=nn.SiLU,
                    skip_identity=True,
                )
                for _ in range(num_blocks)
            ]
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.bottlenecks(self.conv1(x)) + self.conv2(x)


class RepN_CSP_ELAN4(nn.Module):
    """Cross Stage Partial Efficient Layer Aggregation Network block"""

    def __init__(self, in_channels: int, out_channels: int, branch_channels: int, num_blocks: int) -> None:
        super().__init__()
        self.hidden_dim = out_channels
        self.conv1 = Conv2dNormActivation(in_channels, 2 * out_channels, kernel_size=(1, 1), activation_layer=nn.SiLU)
        self.branch1 = nn.Sequential(
            CSPLayer(out_channels, branch_channels, num_blocks),
            Conv2dNormActivation(branch_channels, branch_channels, kernel_size=(3, 3), activation_layer=nn.SiLU),
        )
        self.branch2 = nn.Sequential(
            CSPLayer(branch_channels, branch_channels, num_blocks),
            Conv2dNormActivation(branch_channels, branch_channels, kernel_size=(3, 3), activation_layer=nn.SiLU),
        )
        self.conv2 = Conv2dNormActivation(
            2 * out_channels + 2 * branch_channels, out_channels, kernel_size=(1, 1), activation_layer=nn.SiLU
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        branch1, branch2 = self.conv1(x).split((self.hidden_dim, self.hidden_dim), dim=1)
        branch3 = self.branch1(branch2)
        branch4 = self.branch2(branch3)

        return self.conv2(torch.concat([branch1, branch2, branch3, branch4], dim=1))


class HybridEncoder(nn.Module):
    def __init__(
        self,
        in_channels: list[int],
        hidden_dim: int,
        num_encoder_layers: int,
        dim_feedforward: int,
        dropout: float,
        num_heads: int,
        expansion: float,
        depth_multiplier: float,
    ) -> None:
        super().__init__()
        self.num_levels = len(in_channels)
        self.input_proj = nn.ModuleList(
            [
                nn.Sequential(
                    nn.Conv2d(channels, hidden_dim, kernel_size=(1, 1), bias=False), nn.BatchNorm2d(hidden_dim)
                )
                for channels in in_channels
            ]
        )
        self.encoder = AIFI(
            hidden_dim,
            num_heads=num_heads,
            dim_feedforward=dim_feedforward,
            dropout=dropout,
            num_layers=num_encoder_layers,
        )

        num_blocks = round(3 * depth_multiplier)
        branch_channels = round(expansion * hidden_dim // 2)
        self.lateral_convs = nn.ModuleList()
        self.fpn_blocks = nn.ModuleList()
        for _ in range(self.num_levels - 1, 0, -1):
            self.lateral_convs.append(
                Conv2dNormActivation(hidden_dim, hidden_dim, kernel_size=(1, 1), activation_layer=None)
            )
            self.fpn_blocks.append(RepN_CSP_ELAN4(hidden_dim * 2, hidden_dim, branch_channels, num_blocks))

        self.downsample_convs = nn.ModuleList()
        self.pan_blocks = nn.ModuleList()
        for _ in range(self.num_levels - 1):
            self.downsample_convs.append(SCDown(hidden_dim, hidden_dim))
            self.pan_blocks.append(RepN_CSP_ELAN4(hidden_dim * 2, hidden_dim, branch_channels, num_blocks))

    def set_cache_enabled(self, enabled: bool) -> None:
        self.encoder.set_cache_enabled(enabled)

    def clear_cache(self) -> None:
        self.encoder.clear_cache()

    def forward(self, features: list[torch.Tensor], masks: Optional[list[torch.Tensor]] = None) -> list[torch.Tensor]:
        projected_features = []
        for idx, projection in enumerate(self.input_proj):
            projected_features.append(projection(features[idx]))

        encoder_mask = masks[-1] if masks is not None else None
        projected_features[-1] = self.encoder(projected_features[-1], encoder_mask)

        inner_outputs = [projected_features[-1]]
        for idx, (lateral_conv, fpn_block) in enumerate(zip(self.lateral_convs, self.fpn_blocks)):
            high_feature = lateral_conv(inner_outputs[0])
            low_feature = projected_features[self.num_levels - 2 - idx]
            inner_outputs[0] = high_feature
            high_feature = F.interpolate(high_feature, size=low_feature.shape[-2:], mode="nearest")
            inner_outputs.insert(0, fpn_block(torch.concat([high_feature, low_feature], dim=1)))

        outputs = [inner_outputs[0]]
        for idx, (downsample_conv, pan_block) in enumerate(zip(self.downsample_convs, self.pan_blocks)):
            low_feature = downsample_conv(outputs[-1])
            outputs.append(pan_block(torch.concat([low_feature, inner_outputs[idx + 1]], dim=1)))

        return outputs


class TargetGate(nn.Module):
    def __init__(self, d_model: int) -> None:
        super().__init__()
        self.gate = nn.Linear(2 * d_model, 2 * d_model)
        self.norm = nn.LayerNorm(d_model)

        # Weights initialization
        nn.init.zeros_(self.gate.weight)
        nn.init.zeros_(self.gate.bias)

    def forward(self, target: torch.Tensor, cross_attention: torch.Tensor) -> torch.Tensor:
        target_gate, cross_gate = self.gate(torch.concat([target, cross_attention], dim=-1)).sigmoid().chunk(2, -1)

        return self.norm(target_gate * target + cross_gate * cross_attention)


class TransformerDecoderLayer(nn.Module):
    def __init__(
        self,
        d_model: int,
        dim_feedforward: int,
        dropout: float,
        num_levels: int,
        num_heads: int,
        num_points: list[int],
        method: Literal["default", "discrete"],
        offset_scale: float,
    ) -> None:
        super().__init__()
        self.d_model = d_model
        self.self_attn = MultiheadAttention(d_model, num_heads, attn_drop=dropout)
        self.norm1 = nn.LayerNorm(d_model)
        self.cross_attn = MultiScaleDeformableAttention(
            d_model, num_levels, num_heads, num_points, method=method, offset_scale=offset_scale, with_proj=False
        )
        self.target_gate = TargetGate(d_model)
        self.linear1 = nn.Linear(d_model, dim_feedforward)
        self.linear2 = nn.Linear(dim_feedforward, d_model)
        self.norm3 = nn.LayerNorm(d_model)
        self.activation = nn.ReLU()
        self.dropout = nn.Dropout(dropout)

        # Weights initialization
        nn.init.xavier_uniform_(self.linear1.weight)
        nn.init.xavier_uniform_(self.linear2.weight)

    def forward(
        self,
        target: torch.Tensor,
        query_pos: torch.Tensor,
        reference_points: torch.Tensor,
        memory: torch.Tensor,
        spatial_shapes: torch.Tensor,
        src_shapes: list[list[int]],
        src_split_sizes: list[int],
        level_start_index: torch.Tensor,
        memory_padding_mask: Optional[torch.Tensor],
        valid_ratios: Optional[torch.Tensor],
        attn_mask: Optional[torch.Tensor],
    ) -> torch.Tensor:
        query_key = target + query_pos
        target2 = self.self_attn(query_key, query_key, target, attn_mask=attn_mask)
        target = self.norm1(target + self.dropout(target2))

        target2 = self.cross_attn(
            target + query_pos,
            reference_points,
            memory,
            spatial_shapes,
            src_shapes,
            src_split_sizes,
            level_start_index,
            memory_padding_mask,
            valid_ratios,
        )
        target = self.target_gate(target, self.dropout(target2))
        target2 = self.linear2(self.dropout(self.activation(self.linear1(target))))
        target = target + self.dropout(target2)

        return self.norm3(target.clamp(min=-65504, max=65504))


class Integral(nn.Module):
    def __init__(self, reg_max: int) -> None:
        super().__init__()
        self.reg_max = reg_max

    def forward(self, x: torch.Tensor, project: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        probabilities = F.softmax(x.reshape(x.size(0), x.size(1), 4, self.reg_max + 1), dim=-1)
        distances = F.linear(probabilities.reshape(-1, self.reg_max + 1), project)  # pylint: disable=not-callable
        distances = distances.reshape(x.size(0), x.size(1), 4)

        return (distances, probabilities)


class LQE(nn.Module):
    """
    Localization Quality Estimation head
    """

    def __init__(self, topk: int, hidden_dim: int) -> None:
        super().__init__()
        self.topk = topk
        self.reg_conf = MLP(4 * (topk + 1), [hidden_dim, 1], activation_layer=nn.ReLU)

        # Weights initialization
        nn.init.zeros_(self.reg_conf[-2].weight)
        nn.init.zeros_(self.reg_conf[-2].bias)

    def forward(self, scores: torch.Tensor, probabilities: torch.Tensor) -> torch.Tensor:
        B, length = probabilities.shape[:2]
        topk_probabilities = probabilities.topk(self.topk, dim=-1).values
        statistics = torch.concat([topk_probabilities, topk_probabilities.mean(dim=-1, keepdim=True)], dim=-1)

        return scores + self.reg_conf(statistics.reshape(B, length, -1))


class D_FINEDecoder(nn.Module):
    def __init__(
        self,
        in_channels: list[int],
        hidden_dim: int,
        num_classes: int,
        num_queries: int,
        num_decoder_layers: int,
        num_heads: int,
        dim_feedforward: int,
        dropout: float,
        num_decoder_points: list[int],
        method: Literal["default", "discrete"],
        offset_scale: float,
        query_select_method: Literal["default", "one2many", "agnostic"],
        learn_query_content: bool,
        reg_max: int,
        reg_scale: float,
        eval_idx: int,
        layer_scale: float,
    ) -> None:
        super().__init__()
        self.reparameterized = False
        self.hidden_dim = hidden_dim
        self.num_classes = num_classes
        self.num_queries = num_queries
        self.num_levels = len(in_channels)
        self.num_heads = num_heads
        self.reg_max = reg_max
        self.eval_idx = eval_idx if eval_idx >= 0 else num_decoder_layers + eval_idx
        self.query_select_method = query_select_method

        self.input_proj = nn.ModuleList()
        for channels in in_channels:
            if channels == hidden_dim:
                self.input_proj.append(nn.Identity())
            else:
                self.input_proj.append(
                    nn.Sequential(
                        nn.Conv2d(channels, hidden_dim, kernel_size=(1, 1), bias=False), nn.BatchNorm2d(hidden_dim)
                    )
                )

        self.enc_output = nn.Sequential(nn.Linear(hidden_dim, hidden_dim), nn.LayerNorm(hidden_dim))
        if query_select_method == "agnostic":
            self.enc_score_head = nn.Linear(hidden_dim, 1)
        else:
            self.enc_score_head = nn.Linear(hidden_dim, num_classes)

        self.enc_bbox_head = MLP(hidden_dim, [hidden_dim, hidden_dim, 4], activation_layer=nn.ReLU)

        scaled_dim = round(layer_scale * hidden_dim)
        decoder_layer = TransformerDecoderLayer(
            hidden_dim, dim_feedforward, dropout, self.num_levels, num_heads, num_decoder_points, method, offset_scale
        )
        wide_decoder_layer = TransformerDecoderLayer(
            scaled_dim,
            round(layer_scale * dim_feedforward),
            dropout,
            self.num_levels,
            num_heads,
            num_decoder_points,
            method,
            offset_scale,
        )
        self.layers = nn.ModuleList(
            [copy.deepcopy(decoder_layer) for _ in range(self.eval_idx + 1)]
            + [copy.deepcopy(wide_decoder_layer) for _ in range(num_decoder_layers - self.eval_idx - 1)]
        )

        self.learn_query_content = learn_query_content
        if learn_query_content is True:
            self.target_embed = nn.Embedding(num_queries, hidden_dim)
        else:
            self.target_embed = None

        self.query_pos_head = MLP(4, [2 * hidden_dim, hidden_dim], activation_layer=nn.ReLU)
        self.class_embed = nn.ModuleList(
            [nn.Linear(hidden_dim, num_classes) for _ in range(self.eval_idx + 1)]
            + [nn.Linear(scaled_dim, num_classes) for _ in range(num_decoder_layers - self.eval_idx - 1)]
        )
        self.pre_bbox_head = MLP(hidden_dim, [hidden_dim, hidden_dim, 4], activation_layer=nn.ReLU)
        self.bbox_embed = nn.ModuleList(
            [
                MLP(hidden_dim, [hidden_dim, hidden_dim, 4 * (reg_max + 1)], activation_layer=nn.ReLU)
                for _ in range(self.eval_idx + 1)
            ]
            + [
                MLP(scaled_dim, [scaled_dim, scaled_dim, 4 * (reg_max + 1)], activation_layer=nn.ReLU)
                for _ in range(num_decoder_layers - self.eval_idx - 1)
            ]
        )
        self.lqe = nn.ModuleList([LQE(4, 64) for _ in range(num_decoder_layers)])
        self.integral = Integral(reg_max)
        self.up = nn.Buffer(torch.tensor([0.5]))
        self.reg_scale = nn.Buffer(torch.tensor([reg_scale]))
        self.project = nn.Buffer()

        self.use_cache = True
        self._anchor_cache: dict[str, tuple[torch.Tensor, torch.Tensor]] = {}
        self.reset_parameters()

    def reset_parameters(self) -> None:
        bias_value = -math.log(99)
        for projection in self.input_proj:
            if isinstance(projection, nn.Sequential):
                nn.init.xavier_uniform_(projection[0].weight)

        nn.init.xavier_uniform_(self.enc_output[0].weight)
        nn.init.constant_(self.enc_score_head.bias, bias_value)
        nn.init.zeros_(self.enc_bbox_head[-2].weight)
        nn.init.zeros_(self.enc_bbox_head[-2].bias)
        nn.init.zeros_(self.pre_bbox_head[-2].weight)
        nn.init.zeros_(self.pre_bbox_head[-2].bias)
        nn.init.xavier_uniform_(self.query_pos_head[0].weight)
        nn.init.xavier_uniform_(self.query_pos_head[3].weight)
        if self.target_embed is not None:
            nn.init.xavier_uniform_(self.target_embed.weight)

        for class_embed, bbox_embed in zip(self.class_embed, self.bbox_embed):
            nn.init.constant_(class_embed.bias, bias_value)
            nn.init.zeros_(bbox_embed[-2].weight)
            nn.init.zeros_(bbox_embed[-2].bias)

    def reset_classifier(self, num_classes: int) -> None:
        self.num_classes = num_classes
        if self.query_select_method != "agnostic":
            self.enc_score_head = nn.Linear(self.hidden_dim, num_classes)
            nn.init.constant_(self.enc_score_head.bias, -math.log(99))

        class_embed = []
        for layer in self.layers:
            head = nn.Linear(layer.d_model, num_classes)
            nn.init.constant_(head.bias, -math.log(99))
            class_embed.append(head)

        self.class_embed = nn.ModuleList(class_embed)

    def reparameterize(self) -> None:
        if self.reparameterized is True:
            return

        self.project = nn.Buffer(_weighting_function(self.reg_max, self.up, self.reg_scale))
        self.layers = nn.ModuleList(list(self.layers[: self.eval_idx + 1]))
        self.class_embed = nn.ModuleList(
            [nn.Identity() for _ in range(self.eval_idx)] + [self.class_embed[self.eval_idx]]
        )
        self.bbox_embed = nn.ModuleList(list(self.bbox_embed[: self.eval_idx + 1]))
        self.lqe = nn.ModuleList([nn.Identity() for _ in range(self.eval_idx)] + [self.lqe[self.eval_idx]])
        self.reparameterized = True

    def set_cache_enabled(self, enabled: bool) -> None:
        self.use_cache = enabled
        if enabled is False:
            self.clear_cache()

    def clear_cache(self) -> None:
        self._anchor_cache.clear()

    @staticmethod
    def _get_valid_ratio(mask: torch.Tensor) -> torch.Tensor:
        _, H, W = mask.size()
        valid_h = torch.sum(~mask[:, :, 0], dim=1)
        valid_w = torch.sum(~mask[:, 0, :], dim=1)

        return torch.stack([valid_w.float() / W, valid_h.float() / H], dim=-1)

    def _generate_anchors(
        self,
        spatial_shapes: list[list[int]],
        valid_ratios: Optional[torch.Tensor],
        grid_size: float,
        device: torch.device,
        dtype: torch.dtype,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        cache_key: Optional[str] = None
        use_cache = (
            valid_ratios is None
            and self.use_cache is True
            and torch.jit.is_tracing() is False
            and torch.jit.is_scripting() is False
        )
        if use_cache is True:
            spatial_key = ",".join(f"{int(h)}x{int(w)}" for h, w in spatial_shapes)
            cache_key = f"{spatial_key}_{grid_size}_{device}_{dtype}"
            cached = self._anchor_cache.get(cache_key)
            if cached is not None:
                return cached

        anchors = []
        for level, (H, W) in enumerate(spatial_shapes):
            grid_y, grid_x = torch.meshgrid(
                torch.arange(H, dtype=dtype, device=device), torch.arange(W, dtype=dtype, device=device), indexing="ij"
            )
            grid_xy = torch.stack([grid_x, grid_y], dim=-1)
            valid_wh = torch.tensor([W, H], dtype=dtype, device=device)
            if valid_ratios is None:
                grid_xy = (grid_xy.unsqueeze(0) + 0.5) / valid_wh
            else:
                valid_wh = valid_wh * valid_ratios[:, level]
                grid_xy = (grid_xy.unsqueeze(0) + 0.5) / valid_wh[:, None, None]

            wh = torch.ones_like(grid_xy) * grid_size * (2.0**level)
            anchors.append(torch.concat([grid_xy, wh], dim=-1).reshape(grid_xy.size(0), H * W, 4))

        anchors_tensor = torch.concat(anchors, dim=1)
        valid_mask = ((anchors_tensor > 0.01) * (anchors_tensor < 0.99)).all(dim=-1, keepdim=True)
        anchors_tensor = torch.log(anchors_tensor / (1 - anchors_tensor))
        anchors_tensor = torch.where(valid_mask, anchors_tensor, torch.inf)
        if cache_key is not None:
            self._anchor_cache[cache_key] = (anchors_tensor, valid_mask)

        return (anchors_tensor, valid_mask)

    def _get_decoder_input(
        self,
        memory: torch.Tensor,
        spatial_shapes: list[list[int]],
        valid_ratios: Optional[torch.Tensor],
        memory_padding_mask: Optional[torch.Tensor],
    ) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:
        anchors, valid_mask = self._generate_anchors(spatial_shapes, valid_ratios, 0.05, memory.device, memory.dtype)
        if memory_padding_mask is not None:
            valid_mask = valid_mask & ~memory_padding_mask.unsqueeze(-1)

        memory = valid_mask.to(memory.dtype) * memory
        output_memory = self.enc_output(memory)
        enc_logits = self.enc_score_head(output_memory)
        if memory_padding_mask is not None:
            enc_logits = enc_logits.masked_fill(memory_padding_mask.unsqueeze(-1), float("-inf"))

        if self.query_select_method == "one2many":
            topk_indices = torch.topk(enc_logits.flatten(1), self.num_queries, dim=1).indices // self.num_classes
        else:
            topk_indices = torch.topk(enc_logits.amax(dim=-1), self.num_queries, dim=1).indices

        if anchors.size(0) != memory.size(0):
            anchors = anchors.expand(memory.size(0), -1, -1)

        topk_memory = output_memory.gather(
            dim=1, index=topk_indices.unsqueeze(-1).expand(-1, -1, output_memory.size(-1))
        )
        topk_logits = enc_logits.gather(dim=1, index=topk_indices.unsqueeze(-1).expand(-1, -1, enc_logits.size(-1)))
        topk_anchors = anchors.gather(dim=1, index=topk_indices.unsqueeze(-1).expand(-1, -1, 4))
        topk_bbox_unact = self.enc_bbox_head(topk_memory) + topk_anchors
        if self.target_embed is None:
            target = topk_memory.detach()
        else:
            target = self.target_embed.weight.unsqueeze(0).expand(memory.size(0), -1, -1)

        return (target, topk_bbox_unact.detach(), topk_bbox_unact.sigmoid(), topk_logits)

    @staticmethod
    def _resize_embedding(x: torch.Tensor, size: int) -> torch.Tensor:
        return F.interpolate(x, size=size) if x.size(-1) != size else x

    def forward(
        self,
        features: list[torch.Tensor],
        denoising_class: Optional[torch.Tensor] = None,
        denoising_bbox_unact: Optional[torch.Tensor] = None,
        attn_mask: Optional[torch.Tensor] = None,
        masks: Optional[list[torch.Tensor]] = None,
        return_intermediates: bool = True,
    ) -> tuple[
        torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor
    ]:
        memory_list: list[torch.Tensor] = []
        mask_list: list[torch.Tensor] = []
        spatial_shapes: list[list[int]] = []
        level_start_index: list[int] = [0]
        for idx, projection in enumerate(self.input_proj):
            feature = projection(features[idx])
            H, W = feature.shape[-2:]
            spatial_shapes.append([H, W])
            level_start_index.append(level_start_index[-1] + H * W)
            memory_list.append(feature.flatten(2).permute(0, 2, 1))
            if masks is not None:
                mask_list.append(masks[idx].flatten(1))

        level_start_index.pop()
        memory = torch.concat(memory_list, dim=1)
        memory_padding_mask = torch.concat(mask_list, dim=1) if mask_list else None
        valid_ratios: Optional[torch.Tensor] = None
        if masks is not None:
            valid_ratios = torch.stack([self._get_valid_ratio(mask) for mask in masks], dim=1)
            valid_ratios = valid_ratios.to(dtype=memory.dtype, device=memory.device)

        target, reference_points_unact, enc_bboxes, enc_logits = self._get_decoder_input(
            memory, spatial_shapes, valid_ratios, memory_padding_mask
        )
        if denoising_class is not None and denoising_bbox_unact is not None:
            target = torch.concat([denoising_class, target], dim=1)
            reference_points_unact = torch.concat([denoising_bbox_unact, reference_points_unact], dim=1)

        spatial_shapes_tensor = torch.tensor(spatial_shapes, dtype=torch.long, device=memory.device)
        level_start_index_tensor = torch.tensor(level_start_index, dtype=torch.long, device=memory.device)
        split_sizes = [H * W for H, W in spatial_shapes]
        if self.reparameterized is True:
            project = self.project
        else:
            project = _weighting_function(self.reg_max, self.up, self.reg_scale)

        reference_points_detached = reference_points_unact.sigmoid().detach()
        initial_reference_points = reference_points_detached
        output = target
        output_detached: Optional[torch.Tensor] = None
        accumulated_corners: Optional[torch.Tensor] = None
        pre_bboxes = reference_points_detached
        pre_logits = output
        final_bboxes = reference_points_detached
        final_logits = output
        final_corners = output

        bbox_outputs = []
        logits_outputs = []
        corner_outputs = []
        reference_outputs = []
        for layer_idx, (layer, bbox_head, class_head, lqe) in enumerate(
            zip(self.layers, self.bbox_embed, self.class_embed, self.lqe)
        ):
            if return_intermediates is True or layer_idx <= self.eval_idx:
                query_pos = self.query_pos_head(reference_points_detached).clamp(min=-10, max=10)
                layer_memory = memory
                if layer.d_model != output.size(-1):
                    output = self._resize_embedding(output, layer.d_model)
                    output_detached = output.detach()

                if layer.d_model != memory.size(-1):
                    layer_memory = self._resize_embedding(memory, layer.d_model)

                if layer.d_model != query_pos.size(-1):
                    query_pos = self._resize_embedding(query_pos, layer.d_model)

                if valid_ratios is None:
                    reference_points_input = reference_points_detached.unsqueeze(2)
                else:
                    valid_ratio_boxes = torch.concat([valid_ratios, valid_ratios], dim=-1)
                    reference_points_input = reference_points_detached[:, :, None] * valid_ratio_boxes[:, None]

                output = layer(
                    output,
                    query_pos,
                    reference_points_input,
                    layer_memory,
                    spatial_shapes_tensor,
                    spatial_shapes,
                    split_sizes,
                    level_start_index_tensor,
                    memory_padding_mask,
                    valid_ratios,
                    attn_mask,
                )

                if layer_idx == 0:
                    pre_bboxes = (self.pre_bbox_head(output) + inverse_sigmoid(reference_points_detached)).sigmoid()
                    pre_logits = class_head(output)
                    initial_reference_points = pre_bboxes.detach()

                bbox_input = output if output_detached is None else output + output_detached
                pred_corners = bbox_head(bbox_input)
                if accumulated_corners is not None:
                    pred_corners = pred_corners + accumulated_corners

                integral, corner_probabilities = self.integral(pred_corners, project)
                refined_bboxes = _distance_to_bbox(initial_reference_points, integral, self.reg_scale)

                if return_intermediates is True or layer_idx == self.eval_idx:
                    if layer_idx == 0:
                        logits = lqe(pre_logits, corner_probabilities)
                    else:
                        logits = lqe(class_head(output), corner_probabilities)

                    if return_intermediates is True:
                        bbox_outputs.append(refined_bboxes)
                        logits_outputs.append(logits)
                        corner_outputs.append(pred_corners)
                        reference_outputs.append(initial_reference_points)

                    final_bboxes = refined_bboxes
                    final_logits = logits
                    final_corners = pred_corners

                accumulated_corners = pred_corners
                reference_points_detached = refined_bboxes.detach()
                output_detached = output.detach()

        if return_intermediates is True:
            out_bboxes = torch.stack(bbox_outputs)
            out_logits = torch.stack(logits_outputs)
            out_corners = torch.stack(corner_outputs)
            out_references = torch.stack(reference_outputs)
        else:
            out_bboxes = final_bboxes
            out_logits = final_logits
            out_corners = final_corners
            out_references = initial_reference_points

        return (out_bboxes, out_logits, out_corners, out_references, pre_bboxes, pre_logits, enc_bboxes, enc_logits)


class D_FINE(DetectionBaseNet):
    default_size = (640, 640)

    def __init__(
        self,
        num_classes: int,
        backbone: DetectorBackbone,
        *,
        config: Optional[dict[str, Any]] = None,
        size: Optional[tuple[int, int]] = None,
        export_mode: bool = False,
    ) -> None:
        super().__init__(num_classes, backbone, config=config, size=size, export_mode=export_mode)
        assert self.config is not None, "must set config"

        self.reparameterized = False
        self.num_classes = self.num_classes - 1  # Sigmoid classification has no background logit

        num_backbone_levels: int = self.config.get("num_backbone_levels", 3)
        hidden_dim: int = self.config.get("hidden_dim", 256)
        encoder_hidden_dim: int = self.config.get("encoder_hidden_dim", hidden_dim)
